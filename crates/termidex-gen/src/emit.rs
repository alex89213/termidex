/// The community-standard type palette, as hex.
const TYPE_COLORS: [(&str, u32); 18] = [
    ("normal", 0xA8A77A),
    ("fire", 0xEE8130),
    ("water", 0x6390F0),
    ("electric", 0xF7D02C),
    ("grass", 0x7AC74C),
    ("ice", 0x96D9D6),
    ("fighting", 0xC22E28),
    ("poison", 0xA33EA1),
    ("ground", 0xE2BF65),
    ("flying", 0xA98FF3),
    ("psychic", 0xF95587),
    ("bug", 0xA6B91A),
    ("rock", 0xB6A136),
    ("ghost", 0x735797),
    ("dragon", 0x6F35FC),
    ("dark", 0x705746),
    ("steel", 0xB7B7CE),
    ("fairy", 0xD685AD),
];

/// Writes `generated/data.rs` and `generated/sprites.bin`.
///
/// # Arguments
/// * `out_dir` - the runtime crate's `generated/` directory
/// * `model` - the built species and entry tables
/// * `blob` - the encoded sprites
/// * `slots` - `entry_id * 4 + shiny * 2 + female` to sprite directory index
///
/// # Returns
/// nothing, or the first write or validation error
pub fn write_data(
    out_dir: &Path,
    model: &Model,
    blob: &SpriteBlob,
    slots: &[u32],
) -> Result<(), String> {
    let mut s = String::with_capacity(4 << 20);
    s.push_str(
        "// @generated by termidex-gen from the PokeAPI api-data and sprites repos.\n\
         // Do not edit. Regenerate with: scripts/fetch-data.sh && cargo run -p termidex-gen --release\n\n",
    );

    writeln!(s, "pub const ENTRY_COUNT: usize = {};", model.entries.len()).unwrap();
    writeln!(
        s,
        "pub const SPECIES_COUNT: usize = {};",
        model.species.len()
    )
    .unwrap();
    writeln!(s).unwrap();

    writeln!(
        s,
        "pub static GENERATIONS: [u8; {}] = {:?};",
        model.generations.len(),
        model.generations
    )
    .unwrap();
    writeln!(
        s,
        "pub static REGIONS: [&str; {}] = {:?};",
        model.regions.len(),
        model.regions
    )
    .unwrap();
    writeln!(
        s,
        "pub static SELECTOR_ALIASES: [(&str, &str); {}] = {:?};",
        SELECTOR_ALIASES.len(),
        SELECTOR_ALIASES
    )
    .unwrap();
    writeln!(s).unwrap();

    // types
    writeln!(s, "pub static TYPES: [TypeInfo; {}] = [", model.types.len()).unwrap();
    for slug in &model.types {
        let color = TYPE_COLORS.iter().find(|(n, _)| n == slug).map(|(_, c)| *c);
        let color = match color {
            Some(c) => format!(
                "Some(Rgb({}, {}, {}))",
                (c >> 16) & 0xFF,
                (c >> 8) & 0xFF,
                c & 0xFF
            ),
            None => "None".to_string(),
        };
        writeln!(
            s,
            "    TypeInfo {{ name: {}, color: {color} }},",
            rust_str(&title_case(slug))
        )
        .unwrap();
    }
    writeln!(s, "];\n").unwrap();

    // species
    let offsets = selector_offsets(model);
    writeln!(
        s,
        "pub static SPECIES: [Species; {}] = [",
        model.species.len()
    )
    .unwrap();
    for (i, sp) in model.species.iter().enumerate() {
        let flavor = match &sp.flavor {
            Some(f) => format!("Some({})", rust_str(f)),
            None => "None".to_string(),
        };
        writeln!(
            s,
            "    Species {{ slug: {}, name: {}, genus: {}, flavor: {flavor}, dex: {}, generation: {}, \
             gender_rate: {}, default_entry: {}, entry_start: {}, entry_end: {}, selector_start: {}, \
             selector_end: {} }},",
            rust_str(&sp.slug),
            rust_str(&sp.name),
            rust_str(&sp.genus),
            sp.dex,
            sp.generation,
            sp.gender_rate,
            sp.default_entry,
            sp.entry_start,
            sp.entry_end,
            offsets[i],
            offsets[i] + sp.selectors.len() as u32,
        )
        .unwrap();
    }
    writeln!(s, "];\n").unwrap();

    // entries
    writeln!(
        s,
        "pub static ENTRIES: [Entry; {}] = [",
        model.entries.len()
    )
    .unwrap();
    for e in &model.entries {
        writeln!(
            s,
            "    Entry {{ species: {}, display_name: {}, selector: {}, types: [{}, {}], \
             stats: {:?}, height: {}, weight: {}, flags: {}, generation: {}, region: {} }},",
            e.species_idx,
            rust_str(&e.display_name),
            rust_str(&e.selector),
            e.types[0],
            e.types[1],
            e.stats,
            e.height,
            e.weight,
            e.flags,
            e.generation,
            e.region,
        )
        .unwrap();
    }
    writeln!(s, "];\n").unwrap();

    // flat selector table, one contiguous run per species
    let total_selectors: usize = model.species.iter().map(|sp| sp.selectors.len()).sum();
    writeln!(
        s,
        "pub static SELECTORS: [(&str, u32); {total_selectors}] = ["
    )
    .unwrap();
    for sp in &model.species {
        for (key, id) in &sp.selectors {
            writeln!(s, "    ({}, {id}),", rust_str(key)).unwrap();
        }
    }
    writeln!(s, "];\n").unwrap();

    // sprite directory and slots
    writeln!(
        s,
        "pub static SPRITE_DIR: [(u32, u32); {}] = [",
        blob.directory.len()
    )
    .unwrap();
    for (offset, len) in &blob.directory {
        writeln!(s, "    ({offset}, {len}),").unwrap();
    }
    writeln!(s, "];\n").unwrap();

    writeln!(s, "pub static SPRITE_SLOTS: [u32; {}] = [", slots.len()).unwrap();
    for chunk in slots.chunks(16) {
        s.push_str("   ");
        for v in chunk {
            write!(s, " {v},").unwrap();
        }
        s.push('\n');
    }
    writeln!(s, "];\n").unwrap();

    write_name_maps(&mut s, model)?;

    // Finish validation before changing either committed artifact.
    fs::create_dir_all(out_dir).map_err(|e| e.to_string())?;
    fs::write(out_dir.join("sprites.bin"), &blob.bytes).map_err(|e| e.to_string())?;
    fs::write(out_dir.join("data.rs"), s).map_err(|e| e.to_string())?;
    Ok(())
}

/// Running start offset of each species' selector run in the flat `SELECTORS` table.
fn selector_offsets(model: &Model) -> Vec<u32> {
    let mut offsets = Vec::with_capacity(model.species.len() + 1);
    let mut running = 0u32;
    for sp in &model.species {
        offsets.push(running);
        running += sp.selectors.len() as u32;
    }
    offsets.push(running);
    offsets
}

/// Emits the two phf maps and fails on any normalization collision.
fn write_name_maps(s: &mut String, model: &Model) -> Result<(), String> {
    // species slug and English name only, both pointing at the species' default entry
    let mut names: HashMap<String, (u32, String)> = HashMap::new();
    for sp in &model.species {
        for raw in [sp.slug.as_str(), sp.name.as_str()] {
            let key = normalize(raw);
            if key.is_empty() {
                return Err(format!("species '{}' normalizes to nothing", sp.slug));
            }
            if let Some((prev, prev_raw)) = names.get(&key) {
                if *prev != sp.default_entry {
                    return Err(format!(
                        "name collision on '{key}': '{prev_raw}' and '{raw}' both claim it"
                    ));
                }
                continue;
            }
            names.insert(key, (sp.default_entry, raw.to_string()));
        }
    }

    let mut map = phf_codegen::Map::new();
    let mut sorted: Vec<(&String, &(u32, String))> = names.iter().collect();
    sorted.sort();
    for (key, (id, _)) in &sorted {
        map.entry(key.as_str(), &format!("{id}u32"));
    }
    writeln!(
        s,
        "pub static NAMES: ::phf::Map<&'static str, u32> = {};\n",
        map.build()
    )
    .unwrap();

    // the error path map: a full variety or form slug points at the command that would work
    let mut alts: HashMap<String, (u32, String, String)> = HashMap::new();
    for e in &model.entries {
        let key = normalize(&e.full_slug);
        if names.contains_key(&key) {
            // the slug is already a real name, nothing to suggest
            continue;
        }
        let selector = if e.is_default_entry() {
            String::new()
        } else {
            e.selector.clone()
        };
        if let Some((_, prev_slug, _)) = alts.get(&key) {
            if prev_slug != &e.full_slug {
                return Err(format!(
                    "slug collision on '{key}': '{prev_slug}' and '{}'",
                    e.full_slug
                ));
            }
            continue;
        }
        alts.insert(key, (e.species_idx, e.full_slug.clone(), selector));
    }

    let mut map = phf_codegen::Map::new();
    let mut sorted: Vec<(&String, &(u32, String, String))> = alts.iter().collect();
    sorted.sort();
    let values: Vec<String> = sorted
        .iter()
        .map(|(_, (sp, _, sel))| format!("({sp}u32, {})", rust_str(sel)))
        .collect();
    for ((key, _), value) in sorted.iter().zip(&values) {
        map.entry(key.as_str(), value);
    }
    writeln!(
        s,
        "pub static ALT_SLUGS: ::phf::Map<&'static str, (u32, &'static str)> = {};",
        map.build()
    )
    .unwrap();

    Ok(())
}

/// Escapes a string so it can be pasted into generated Rust source.
fn rust_str(s: &str) -> String {
    let mut out = String::with_capacity(s.len() + 2);
    out.push('"');
    for ch in s.chars() {
        match ch {
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            '\t' => out.push_str("\\t"),
            c if (c as u32) < 0x20 => {
                write!(out, "\\u{{{:x}}}", c as u32).unwrap();
            }
            c => out.push(c),
        }
    }
    out.push('"');
    out
}

/// Writes the human-readable data report.
///
/// # Arguments
/// * `path` - where to put `coverage.txt`
/// * `model` - the built tables
/// * `blob` - the encoded sprites, for the size summary
///
/// # Returns
/// nothing, or a write error
pub fn write_coverage(path: &Path, model: &Model, blob: &SpriteBlob) -> Result<(), String> {
    let mut f = fs::File::create(path).map_err(|e| e.to_string())?;
    let w = &mut f;
    let mut oops = Ok(());
    macro_rules! line {
        ($($a:tt)*) => { if oops.is_ok() { oops = writeln!(w, $($a)*).map_err(|e| e.to_string()); } };
    }

    line!("termidex data coverage report");
    line!("=============================");
    line!();
    line!("counts");
    line!("------");
    line!("species                 {}", model.species.len());
    line!("entries                 {}", model.entries.len());
    let default_entries = model
        .entries
        .iter()
        .filter(|e| e.is_default_entry())
        .count();
    let alt_varieties = model
        .entries
        .iter()
        .filter(|e| e.flags & F_DEFAULT_VARIETY == 0 && e.flags & F_DEFAULT_FORM != 0)
        .count();
    let alt_forms = model
        .entries
        .iter()
        .filter(|e| e.flags & F_DEFAULT_FORM == 0)
        .count();
    line!("  default entries       {default_entries}");
    line!("  alternate varieties   {alt_varieties}");
    line!("  alternate forms       {alt_forms}");
    line!("types                   {}", model.types.len());
    line!("generations             {:?}", model.generations);
    line!();
    line!("sprite blob");
    line!("-----------");
    line!("source png bytes        {}", blob.raw_png_bytes);
    line!("pngs decoded            {}", blob.decoded_count);
    line!("unique sprites stored   {}", blob.directory.len());
    line!("sprites.bin bytes       {}", blob.bytes.len());
    line!("largest palette         {}", blob.max_palette);
    line!();

    section(
        &mut oops,
        w,
        "excluded entries (no sprite)",
        model.excluded.len(),
    );
    for (slug, why) in &model.excluded {
        line!("  {slug}: {why}");
    }
    line!();

    section(
        &mut oops,
        w,
        "entries without a shiny sprite",
        model.no_shiny.len(),
    );
    for slug in &model.no_shiny {
        line!("  {slug}");
    }
    line!();

    section(
        &mut oops,
        w,
        "entries with a female sprite but no shiny female sprite",
        model.no_shiny_female.len(),
    );
    for slug in &model.no_shiny_female {
        line!("  {slug}");
    }
    line!();

    section(
        &mut oops,
        w,
        "entries whose female sprite is indistinguishable from the default, so has_female is cleared",
        model.female_same_as_default.len(),
    );
    for slug in &model.female_same_as_default {
        line!("  {slug}");
    }
    line!();

    section(
        &mut oops,
        w,
        "entries whose female is its own entry (--form female), so their female sprite is dropped",
        model.female_is_own_entry.len(),
    );
    for slug in &model.female_is_own_entry {
        line!("  {slug}");
    }
    line!();

    section(
        &mut oops,
        w,
        "species where has_gender_differences disagrees with the sprites on disk",
        model.gender_mismatch.len(),
    );
    for note in &model.gender_mismatch {
        line!("  {note}");
    }
    line!();

    section(
        &mut oops,
        w,
        "species without English flavor text",
        model.no_flavor.len(),
    );
    for slug in &model.no_flavor {
        line!("  {slug}");
    }
    line!();

    section(
        &mut oops,
        w,
        "entries whose own generation differs from their species'",
        model.generation_differs.len(),
    );
    for (slug, species_gen, entry_gen) in &model.generation_differs {
        line!("  {slug}: species is gen {species_gen}, entry is gen {entry_gen}");
    }
    line!();

    section(
        &mut oops,
        w,
        "entries whose games map to no region",
        model.region_unknown.len(),
    );
    for note in &model.region_unknown {
        line!("  {note}");
    }
    line!();

    let mut per_region: BTreeMap<&str, usize> = BTreeMap::new();
    for (_, region, _) in &model.regional {
        *per_region.entry(region).or_default() += 1;
    }
    section(&mut oops, w, "entries per region", per_region.len());
    for (region, count) in &per_region {
        line!("  {region:<8} {count}");
    }
    line!();

    section(
        &mut oops,
        w,
        "region of every entry, from the games that introduced it",
        model.regional.len(),
    );
    for (slug, region, version_group) in &model.regional {
        line!("  {slug:<34} {region:<8} {version_group}");
    }
    line!();

    section(
        &mut oops,
        w,
        "slugs that do not start with their species slug",
        model.unprefixed.len(),
    );
    for slug in &model.unprefixed {
        line!("  {slug}");
    }
    line!();

    section(
        &mut oops,
        w,
        "lookup keys holding a character with no explicit normalization rule",
        model.odd_keys.len(),
    );
    for key in &model.odd_keys {
        line!("  {key}");
    }
    line!();

    let with_selectors = model
        .species
        .iter()
        .filter(|sp| !sp.selectors.is_empty())
        .count();
    section(&mut oops, w, "selectors per species", with_selectors);
    for sp in &model.species {
        if sp.selectors.is_empty() {
            continue;
        }
        let keys: Vec<&str> = sp.selectors.iter().map(|(k, _)| k.as_str()).collect();
        line!("  {:<24} {}", sp.slug, keys.join(", "));
    }

    oops
}

/// Writes a section heading with its item count.
fn section(oops: &mut Result<(), String>, w: &mut fs::File, title: &str, count: usize) {
    if oops.is_ok() {
        *oops = writeln!(w, "{title} ({count})\n{}", "-".repeat(title.len() + 6))
            .map_err(|e| e.to_string());
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::model::{Model, Species};

    /// A model holding nothing but the species given, which is all the name maps look at.
    fn model_with(species: Vec<(&str, &str)>) -> Model {
        Model {
            species: species
                .into_iter()
                .enumerate()
                .map(|(i, (slug, name))| Species {
                    slug: slug.to_string(),
                    name: name.to_string(),
                    genus: String::new(),
                    flavor: None,
                    dex: i as u16 + 1,
                    generation: 1,
                    gender_rate: 4,
                    default_entry: i as u32,
                    entry_start: i as u32,
                    entry_end: i as u32 + 1,
                    selectors: Vec::new(),
                })
                .collect(),
            entries: Vec::new(),
            types: Vec::new(),
            generations: vec![1],
            excluded: Vec::new(),
            no_shiny: Vec::new(),
            no_shiny_female: Vec::new(),
            no_flavor: Vec::new(),
            regions: vec!["kanto".to_string()],
            regional: Vec::new(),
            region_unknown: Vec::new(),
            generation_differs: Vec::new(),
            unprefixed: Vec::new(),
            odd_keys: Vec::new(),
            gender_mismatch: Vec::new(),
            female_same_as_default: Vec::new(),
            female_is_own_entry: Vec::new(),
        }
    }

    /// distinct species should each get their keys without complaint
    #[test]
    fn distinct_names_emit() {
        let model = model_with(vec![("mr-mime", "Mr. Mime"), ("pikachu", "Pikachu")]);
        let mut out = String::new();
        write_name_maps(&mut out, &model).expect("should emit");
        assert!(out.contains("NAMES"));
        assert!(out.contains("ALT_SLUGS"));
    }

    /// a species slug and another species' English name folding to one key must fail loudly
    #[test]
    fn colliding_names_fail() {
        // "Mr. Mime" and "mrmime" both normalize to mrmime, but they are different species
        let model = model_with(vec![("mr-mime", "Mr. Mime"), ("mrmime", "Fake Mime")]);
        let mut out = String::new();
        let error = write_name_maps(&mut out, &model).expect_err("a collision should fail");
        assert!(error.contains("collision"), "got: {error}");
        assert!(error.contains("mrmime"), "got: {error}");
    }

    /// Validation failure must leave both files from the previous generation intact.
    #[test]
    fn invalid_names_do_not_overwrite_generated_artifacts() {
        let unique = std::time::SystemTime::now()
            .duration_since(std::time::UNIX_EPOCH)
            .unwrap()
            .as_nanos();
        let out_dir =
            std::env::temp_dir().join(format!("termidex-emit-{}-{unique}", std::process::id()));
        fs::create_dir_all(&out_dir).unwrap();
        fs::write(out_dir.join("sprites.bin"), b"previous sprites").unwrap();
        fs::write(out_dir.join("data.rs"), b"previous tables").unwrap();

        let model = model_with(vec![("mr-mime", "Mr. Mime"), ("mrmime", "Fake Mime")]);
        let error = write_data(&out_dir, &model, &SpriteBlob::new(), &[]).unwrap_err();
        assert!(error.contains("collision"));
        assert_eq!(
            fs::read(out_dir.join("sprites.bin")).unwrap(),
            b"previous sprites"
        );
        assert_eq!(
            fs::read(out_dir.join("data.rs")).unwrap(),
            b"previous tables"
        );
        fs::remove_dir_all(out_dir).unwrap();
    }

    /// a slug and its own English name folding together is fine, they point at the same species
    #[test]
    fn a_species_may_collide_with_itself() {
        let model = model_with(vec![("hooh", "Ho-Oh")]);
        let mut out = String::new();
        write_name_maps(&mut out, &model).expect("one species, one entry, no conflict");
    }

    /// generated strings have to survive being pasted into Rust source
    #[test]
    fn strings_are_escaped() {
        assert_eq!(rust_str("plain"), "\"plain\"");
        assert_eq!(rust_str("say \"hi\""), "\"say \\\"hi\\\"\"");
        assert_eq!(rust_str("back\\slash"), "\"back\\\\slash\"");
        assert_eq!(rust_str("two\nlines"), "\"two\\nlines\"");
        // accents and the gender signs go through untouched, the file is utf8
        assert_eq!(rust_str("Nidoran♀"), "\"Nidoran♀\"");
    }
}
